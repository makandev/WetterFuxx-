let current = 'de';

export function setLang(lang) {
  current = LANGS.includes(lang) ? lang : 'de';
}
export function getLang() {
  return current;
}
export function t(key, vars) {
  let str = (DICT[current] && DICT[current][key]);
  if (str === undefined) str = (DICT.de[key] !== undefined ? DICT.de[key] : key);
  if (typeof str === 'string' && vars) {
    for (const k in vars) str = str.replace(`{${k}}`, vars[k]);
  }
  return str;
}
